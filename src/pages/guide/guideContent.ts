import type { PageId, Track } from '../../app/store'

/**
 * 「使用說明」頁的內容。電梯、手臂共用同一套結構，差別的地方用 track 換字。
 * 文字裡提到的按鈕、標題要跟畫面一致：`guideContent.test.ts` 會去對原始碼，改了畫面用字要一起改這裡。
 */

export interface GuideSection {
  /** 頁面上的 id，樓層頁的「怎麼用這一頁？」用它跳過來 */
  id: string
  /** 「前往」按鈕去哪一頁 */
  page: PageId
  floor: string
  title: string
  /** 這一層在做什麼，一兩句話 */
  what: string
  steps: string[]
  /** 看什麼：讀圖、讀數字的重點 */
  look: string[]
  /** 卡住了：[症狀, 怎麼辦] */
  stuck: [string, string][]
}

export interface GuideStart {
  floor: string
  page: PageId
  text: string
}

export interface GuideTerm {
  name: string
  text: string
}

export interface GuideFaq {
  q: string
  a: string
}

export interface GuideContent {
  intro: string
  /** 第一次用：照順序走一遍 */
  start: GuideStart[]
  sections: GuideSection[]
  terms: GuideTerm[]
  faq: GuideFaq[]
}

