import type { FlywheelGains, FlywheelKnobs, FlywheelMechanism, ShotPlan } from '../flywheel/flywheel'
import { convert, convertArm, jd } from './index'
import { flywheelToRotations } from './flywheel'
import { t } from '../lang'

/**
 * REV SPARK MAX／Flex（REVLib 2026）的設定片段。換算跟 Phoenix 6 一樣在這裡做：
 * 用 encoder 的換算係數讓位置單位是「機構轉幾圈」、速度單位是「機構每秒轉幾圈（rps）」，
 * 這樣增益的數值就是 Phoenix 6 轉數制那一組（kV V/rps、kA V/(rps/s)、kP V/rot）。
 *
 * 兩個要上機確認的地方（沒有真機可以測，文件也沒寫死）：
 * - kS、kV、kA、kG、kCos 是伏特；SPARK 的 P、I、D 輸出是工作週期（-1～1），所以除以 NOMINAL_VOLTS（12 V）。
 * - 速度單位照 encoder 的 velocityConversionFactor，所以 MAXMotion 的巡航速度、加速度也是 rps、rps/s。
 */

/** SPARK 的 P、I、D 輸出是工作週期；電壓 → 工作週期用這個電壓除（決策 144） */
export const NOMINAL_VOLTS = 12

const SOURCE_LABEL: Record<ParameterSet['source'], [string, string]> = {
  theory: ['理論值', 'theory'],
  tuning: ['調參建議值', 'tuning suggestion'],
  custom: ['自訂', 'custom'],
  measured: ['實測值', 'measured'],
}
const deg = (rad: number) => jd(Math.round((rad * 180) / Math.PI * 1000) / 1000)
const src = (s: ParameterSet['source']) => t(SOURCE_LABEL[s][0], SOURCE_LABEL[s][1])

const IMPORTS = [
  'com.revrobotics.spark.FeedbackSensor',
  'com.revrobotics.spark.config.SparkMaxConfig',
]

function importLines(extra: string[] = []): string {
  return [...IMPORTS, ...extra].map((i) => `import ${i};`).join('\n')
}

/** 電梯：Slot 0（往上）＋ MAXMotion 位置控制，重力用 kG */
export function revElevatorJava(ps: ParameterSet, now = new Date()): string {
  const c = convert(ps)
  const g = c.slot0
  const down = c.slot1
  return `package frc.robot.subsystems.elevator;

${importLines()}

/**
 * ${t(`由電梯調參工作站產生（REV SPARK，REVLib 2026）：${src(ps.source)}，${now.toISOString()}。`, `Generated by the elevator tuning workstation (REV SPARK, REVLib 2026): ${src(ps.source)}, ${now.toISOString()}.`)}
 * ${t('位置單位是「鼓輪轉幾圈」，速度是 rps：靠下面的 encoder 換算係數，SPARK 的數字就跟網站的轉數制一樣。', 'Position is “drum rotations” and velocity is rps: the encoder conversion factors below make the SPARK numbers match the site’s rotation units.')}
 * ${t('這個檔案進版本控制，是參數的最終依據；網頁上改的數字要重新產生並 commit 才算數。', 'Keep this file in version control; it is the source of truth. Numbers changed on the site only count once you regenerate and commit.')}
 */
public final class ElevatorRevConfig {
  private ElevatorRevConfig() {}

  public static final double GEAR_RATIO = ${jd(c.sensorToMechanismRatio)};
  /** ${t(`機構座標 1 圈的公尺數${ps.mechanism.controlTop ? '（最上層高度）' : '（鼓輪線位移）'}`, `Meters per mechanism rotation${ps.mechanism.controlTop ? ' (top-stage height)' : ' (drum travel)'}`)} */
  public static final double METERS_PER_ROTATION = ${jd(c.metersPerRotation)};
  /** ${t('SPARK 的 P、I、D 輸出是工作週期（-1～1），增益用這個電壓換算；前饋（kS、kV、kA、kG）本來就是伏特', 'SPARK’s P, I, D output is duty cycle (-1 to 1), so gains are divided by this voltage; the feedforward terms (kS, kV, kA, kG) are already volts')} */
  public static final double NOMINAL_VOLTS = ${jd(NOMINAL_VOLTS)};

  /** ${t(`MAXMotion 巡航速度（rps）＝ ${jd(ps.motionMagic.cruiseVelocity)} m/s`, `MAXMotion cruise velocity (rps) = ${jd(ps.motionMagic.cruiseVelocity)} m/s`)} */
  public static final double CRUISE_VELOCITY = ${jd(c.cruiseVelocity)};
  /** ${t(`MAXMotion 加速度（rps/s）＝ ${jd(ps.motionMagic.acceleration)} m/s²`, `MAXMotion acceleration (rps/s) = ${jd(ps.motionMagic.acceleration)} m/s²`)} */
  public static final double ACCELERATION = ${jd(c.acceleration)};
${
  down
    ? `
  /** ${t('往下移動的前饋（摩擦不對稱時）：REV 沒有自動換，往下走時用 Slot 1 或自己加進 arbFeedforward', 'Feedforward for moving down (asymmetric friction): REV does not switch automatically; use Slot 1 or add it as the arbitrary feedforward when moving down')} */
  public static final double DOWN_KS = ${jd(down.kS)};
  public static final double DOWN_KG = ${jd(down.kG)};
`
    : ''
}
  public static SparkMaxConfig config() {
    SparkMaxConfig config = new SparkMaxConfig();
    // ${t('位置 = 鼓輪轉幾圈，速度 = 鼓輪 rps（SPARK 內建速度是馬達 RPM）', 'position = drum rotations, velocity = drum rps (SPARK’s built-in velocity is motor RPM)')}
    config.encoder
        .positionConversionFactor(1.0 / GEAR_RATIO)
        .velocityConversionFactor(1.0 / GEAR_RATIO / 60.0);
    config.closedLoop
        .feedbackSensor(FeedbackSensor.kPrimaryEncoder)
        .p(${jd(g.kP)} / NOMINAL_VOLTS)
        .i(${jd(g.kI)} / NOMINAL_VOLTS)
        .d(${jd(g.kD)} / NOMINAL_VOLTS);
    config.closedLoop.feedForward
        .kS(${jd(g.kS)})
        .kV(${jd(g.kV)})
        .kA(${jd(g.kA)})
        .kG(${jd(g.kG)});
    config.closedLoop.maxMotion
        .cruiseVelocity(CRUISE_VELOCITY)
        .maxAcceleration(ACCELERATION)
        .allowedProfileError(0.002 / METERS_PER_ROTATION); // ${t('到位誤差 2 mm', 'position tolerance 2 mm')}
    return config;
  }

  // ${t('使用：motor.configure(ElevatorRevConfig.config(), ResetMode.kResetSafeParameters, PersistMode.kNoPersistParameters);', 'Usage: motor.configure(ElevatorRevConfig.config(), ResetMode.kResetSafeParameters, PersistMode.kNoPersistParameters);')}
  // ${t('        controller.setSetpoint(meters / METERS_PER_ROTATION, ControlType.kMAXMotionPositionControl);', '        controller.setSetpoint(meters / METERS_PER_ROTATION, ControlType.kMAXMotionPositionControl);')}
}
`
}

/** 手臂：重力用 kCos（kG·cos θ），位置 0 = 水平 */
export function revArmJava(ps: ArmParameterSet, now = new Date()): string {
  const c = convertArm(ps)
  const g = c.slot0
  const m = ps.mechanism
  const cancoder = m.encoder === 'cancoder'
  return `package frc.robot.subsystems.arm;

${importLines()}

/**
 * ${t(`由手臂調參工作站產生（REV SPARK，REVLib 2026）：${src(ps.source)}，${now.toISOString()}。`, `Generated by the arm tuning workstation (REV SPARK, REVLib 2026): ${src(ps.source)}, ${now.toISOString()}.`)}
 * ${t('位置單位是「手臂轉幾圈」，0 = 水平、往上為正；kCos 用這個位置算 cos。', 'Position is “arm rotations”, 0 = horizontal and up is positive; kCos uses this position for the cosine.')}
 * ${t('這個檔案進版本控制，是參數的最終依據；網頁上改的數字要重新產生並 commit 才算數。', 'Keep this file in version control; it is the source of truth. Numbers changed on the site only count once you regenerate and commit.')}
 */
public final class ArmRevConfig {
  private ArmRevConfig() {}

  /** ${t('馬達圈數 : 手臂 1 圈', 'Motor turns : 1 arm turn')} */
  public static final double GEAR_RATIO = ${jd(m.gearRatio)};
  /** ${t('可以動的角度範圍（度，0 = 水平），軟體限位和子系統限制目標用', 'Allowed angle range (deg, 0 = horizontal), used for software limits and clamping goals')} */
  public static final double MIN_ANGLE_DEG = ${deg(m.minAngle)};
  public static final double MAX_ANGLE_DEG = ${deg(m.maxAngle)};
  /** ${t('SPARK 的 P、I、D 輸出是工作週期（-1～1），增益用這個電壓換算；前饋本來就是伏特', 'SPARK’s P, I, D output is duty cycle (-1 to 1), so gains are divided by this voltage; the feedforward is already volts')} */
  public static final double NOMINAL_VOLTS = ${jd(NOMINAL_VOLTS)};

  /** ${t(`MAXMotion 巡航速度（手臂 rps）＝ ${jd((ps.motionMagic.cruiseVelocity * 180) / Math.PI)} °/s`, `MAXMotion cruise velocity (arm rps) = ${jd((ps.motionMagic.cruiseVelocity * 180) / Math.PI)} °/s`)} */
  public static final double CRUISE_VELOCITY = ${jd(c.cruiseVelocity)};
  /** ${t(`MAXMotion 加速度（手臂 rps/s）＝ ${jd((ps.motionMagic.acceleration * 180) / Math.PI)} °/s²`, `MAXMotion acceleration (arm rps/s) = ${jd((ps.motionMagic.acceleration * 180) / Math.PI)} °/s²`)} */
  public static final double ACCELERATION = ${jd(c.acceleration)};

  public static SparkMaxConfig config() {
    SparkMaxConfig config = new SparkMaxConfig();
    // ${t('位置 = 手臂轉幾圈，速度 = 手臂 rps', 'position = arm rotations, velocity = arm rps')}
    config.encoder
        .positionConversionFactor(1.0 / GEAR_RATIO)
        .velocityConversionFactor(1.0 / GEAR_RATIO / 60.0);
    config.closedLoop
        .feedbackSensor(FeedbackSensor.kPrimaryEncoder)
        .p(${jd(g.kP)} / NOMINAL_VOLTS)
        .i(${jd(g.kI)} / NOMINAL_VOLTS)
        .d(${jd(g.kD)} / NOMINAL_VOLTS);
    // ${t('手臂用 kCos，不是 kG；kCosRatio = 1：上面的換算係數讓感測器讀到的就是手臂轉幾圈', 'Arms use kCos, not kG; kCosRatio = 1 because the conversion factor above already makes the sensor read arm rotations')}
    config.closedLoop.feedForward
        .kS(${jd(g.kS)})
        .kV(${jd(g.kV)})
        .kA(${jd(g.kA)})
        .kCos(${jd(g.kG)})
        .kCosRatio(1.0);
    config.closedLoop.maxMotion
        .cruiseVelocity(CRUISE_VELOCITY)
        .maxAcceleration(ACCELERATION)
        .allowedProfileError(Math.toRadians(1.0) / (2 * Math.PI)); // ${t('到位誤差 1°', 'position tolerance 1°')}
    return config;
  }

  // ${cancoder ? t('你在網站選了 CANcoder，SPARK 不能接；要用絕對編碼器請改接 REV Through Bore Encoder（接 SPARK 的 absolute encoder 腳位），並把 feedbackSensor 改成 FeedbackSensor.kAbsoluteEncoder。', 'You picked a CANcoder on the site, which a SPARK can’t read; to use an absolute encoder, switch to a REV Through Bore Encoder (SPARK absolute-encoder port) and change feedbackSensor to FeedbackSensor.kAbsoluteEncoder.') : t('用內建編碼器：開機時手臂要靠在已知角度，程式再把位置設成那個角度（encoder.setPosition）。', 'With the built-in encoder, the arm must rest at a known angle at power-up, and the code then sets the position to that angle (encoder.setPosition).')}
  // ${t('使用：controller.setSetpoint(angleRad / (2 * Math.PI), ControlType.kMAXMotionPositionControl);', 'Usage: controller.setSetpoint(angleRad / (2 * Math.PI), ControlType.kMAXMotionPositionControl);')}
}
`
}

/** 射球飛輪：速度控制，沒有重力項；有加速度限制就用 MAXMotion 速度模式 */
export function revFlywheelJava(g: FlywheelGains, mech: FlywheelMechanism, knobs: FlywheelKnobs, plan: ShotPlan): string {
  const TAU = 2 * Math.PI
  const r = flywheelToRotations(g)
  const magic = plan.accel > 0
  const lines = [
    t('// 射球飛輪（REV SPARK，REVLib 2026）：速度單位是飛輪的 rps', '// Flywheel shooter (REV SPARK, REVLib 2026): velocity is in flywheel rps'),
    'SparkMaxConfig config = new SparkMaxConfig();',
    `config.encoder.velocityConversionFactor(1.0 / ${jd(mech.gearRatio)} / 60.0); // ${t('馬達 RPM → 飛輪 rps', 'motor RPM → flywheel rps')}`,
    `config.closedLoop.p(${jd(r.kP)} / ${jd(NOMINAL_VOLTS)}).i(${jd(r.kI)} / ${jd(NOMINAL_VOLTS)}).d(${jd(r.kD)} / ${jd(NOMINAL_VOLTS)}); // ${t('V 除以 12 = SPARK 的工作週期增益', 'V divided by 12 = the SPARK duty-cycle gain')}`,
    'config.closedLoop.feedForward',
    `    .kS(${jd(r.kS)}) // V`,
    `    .kV(${jd(r.kV)}) // V/rps`,
    `    .kA(${jd(r.kA)}); // V/(rps/s)${magic ? '' : t('，只在 MAXMotion 速度模式有用', ', only used in MAXMotion velocity mode')}`,
  ]
  if (magic) lines.push(`config.closedLoop.maxMotion.maxAcceleration(${jd(plan.accel / TAU)}); // rps/s`)
  if (knobs.noReverse) lines.push(t('// 不要反向煞車：SPARK 要在程式裡把輸出夾在 0 以上（例如 setpoint 小於實際速度時改用 coast），沒有 Phoenix 的 PeakReverseVoltage', '// No reverse braking: on a SPARK, clamp the output at 0 or above in code (for example let it coast when the setpoint is below the actual speed); there is no PeakReverseVoltage like Phoenix'))
  if (knobs.statorLimit > 0) lines.push(`config.smartCurrentLimit((int) ${Math.round(knobs.statorLimit)}); // A ${t('（SPARK 的限流是 smart current limit，不是 Phoenix 的 stator limit）', '(the SPARK limit is a smart current limit, not a Phoenix stator limit)')}`)
  lines.push('motor.configure(config, ResetMode.kResetSafeParameters, PersistMode.kNoPersistParameters);')
  if (mech.motorCount > 1) lines.push(t('// 其他馬達設成 follow（方向相反的話 follow 第二個參數用 true）', '// Set the other motors to follow (pass true as the second follow argument if they spin the other way)'))
  lines.push('')
  lines.push(`controller.setSetpoint(${jd(plan.target / TAU)}, ${magic ? 'ControlType.kMAXMotionVelocityControl' : 'ControlType.kVelocity'}); // ${t('目標 rps', 'target rps')}`)
  return lines.join('\n')
}
